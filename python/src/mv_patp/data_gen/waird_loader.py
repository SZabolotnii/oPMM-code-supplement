"""WAIR-D ray-tracing channel loader for §V cross-environment evaluation.

WAIR-D (Wireless AI Research Dataset, arXiv:2212.02159) provides multipath
channel impulse responses generated by PyLayers 3D ray-tracing across 10 000
random indoor environments (Scenario 1).  Each environment directory contains
``H_{freq_int}_{freq_dec}_G.npy`` files (one per frequency band) where the
.npy object is a dict keyed by ``bs{i}_ue{j}`` — multipath complex-coefficient
arrays for each base-station / user-equipment pair.

Narrowband model: ``H_complex[i, j] = sum(path_coefficients[bs{i}_ue{j}])``.
This collapses the multipath to a single complex gain per element, yielding a
``(n_bs, n_ue)`` MIMO channel matrix per environment.

Real-equivalent conversion mirrors ``deepmimo_loader``:
``H_real = [Re(H_c); Im(H_c)]``, giving shape ``(2 * n_bs, n_ue)``.

Satisfies Requirement R10.3 (cross-environment generalisation ≥ 3 environments).
Task: §17.1.

References
----------
Yoo, J.-H. et al. (2022). WAIR-D: Wireless AI Research Dataset. arXiv:2212.02159.
"""

from __future__ import annotations

import logging
from pathlib import Path

import numpy as np

from mv_patp.data_gen.matrix_mal_dgp import sample_matrix_mal

logger = logging.getLogger(__name__)

# Mapping from numeric frequency (GHz) to the filename fragment used by WAIR-D.
# Format: "H_{int_part}_{dec_part}_G.npy" where 28.0 → "H_28_0_G".
_FREQ_TO_FNAME: dict[float, str] = {
    2.6: "H_2_6_G",
    6.0: "H_6_0_G",
    28.0: "H_28_0_G",
    60.0: "H_60_0_G",
    100.0: "H_100_0_G",
}


def _env_dir(data_dir: Path, env_id: int) -> Path:
    return data_dir / f"{env_id:05d}"


def _load_channel_matrix(env_path: Path, freq_ghz: float) -> np.ndarray:
    """Load narrowband MIMO channel matrix from a WAIR-D environment directory.

    Parameters
    ----------
    env_path : Path
        Path to the environment directory (e.g. ``scenario_1/00001/``).
    freq_ghz : float
        Carrier frequency in GHz; must be one of {2.6, 6.0, 28.0, 60.0, 100.0}.

    Returns
    -------
    H_complex : np.ndarray, shape (n_bs, n_ue), complex128
        Narrowband channel matrix obtained by summing all multipath coefficients
        for each BS-UE pair.
    """
    if freq_ghz not in _FREQ_TO_FNAME:
        raise ValueError(
            f"freq_ghz={freq_ghz} not in supported set {set(_FREQ_TO_FNAME)}."
        )
    fname = env_path / (_FREQ_TO_FNAME[freq_ghz] + ".npy")
    if not fname.exists():
        raise FileNotFoundError(f"Channel file not found: {fname}")

    data = np.load(fname, allow_pickle=True).item()  # dict bs{i}_ue{j} → array
    # Determine antenna counts from key names.
    keys = list(data.keys())
    n_bs = max(int(k.split("_ue")[0][2:]) for k in keys) + 1
    n_ue = max(int(k.split("_ue")[1]) for k in keys) + 1

    H = np.zeros((n_bs, n_ue), dtype=np.complex128)
    for i in range(n_bs):
        for j in range(n_ue):
            key = f"bs{i}_ue{j}"
            if key in data:
                H[i, j] = data[key].sum()  # narrowband: collapse multipath
    return H


def _real_equiv(H_complex: np.ndarray) -> np.ndarray:
    """Vertical real-equivalent stack: (n_bs, n_ue) complex → (2*n_bs, n_ue) real."""
    return np.concatenate([H_complex.real, H_complex.imag], axis=0).astype(np.float64)


def _scale_noise_to_snr(HS: np.ndarray, N_unit: np.ndarray, snr_db: float) -> np.ndarray:
    sig_power = float(np.mean(HS * HS))
    noise_power = float(np.mean(N_unit * N_unit))
    if noise_power <= 0.0:
        raise ValueError("Noise sample has zero power; cannot rescale.")
    target_noise_power = sig_power / (10.0 ** (snr_db / 10.0))
    return float(np.sqrt(target_noise_power / noise_power)) * N_unit


def load_waird(
    env_id: int,
    snr_db: float,
    n_train: int,
    *,
    p: int = 2,
    freq_ghz: float = 28.0,
    alpha_mal: float = 1.0,
    noise_kind: str = "student_t_4",
    seed: int = 42,
    data_dir: str | Path = "data/waird/extracted/WAIR-D/data/scenario_1",
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Build a ``(Y, S, H_truth)`` triple from a WAIR-D ray-traced environment.

    Loads the narrowband MIMO channel from environment ``env_id``, draws a
    unit-power Gaussian pilot matrix ``S``, adds noise at the target SNR,
    and returns ``Y = H_truth @ S + N``.

    Parameters
    ----------
    env_id : int
        WAIR-D environment index in range [1, 10000].
    snr_db : float
        Target signal-to-noise ratio in dB.
    n_train : int
        Length of the training sequence (columns of ``S`` and ``Y``).
    p : int, default 2
        Number of TX antennas (UE columns selected from the channel matrix).
    freq_ghz : float, default 28.0
        Carrier frequency in GHz; selects the ``H_*_G.npy`` file.
    alpha_mal : float, default 1.0
        Shape parameter for matrix-MAL noise (only used when
        ``noise_kind="matrix_mal"``).
    noise_kind : str, default ``"student_t_4"``
        Noise distribution: ``"matrix_mal"`` or ``"student_t_<df>"``
        (e.g. ``"student_t_4"``).  Student-t is preferred for
        ``k >= 10`` where the MAL alpha constraint clips heavily.
    seed : int, default 42
        RNG seed per AGENTS.md §6.2. Pilot matrix uses ``seed``,
        noise uses ``seed + 1``, UE column selection uses ``seed + 2``.
    data_dir : str or Path
        Root directory of WAIR-D Scenario 1 environments.

    Returns
    -------
    (Y, S, H_truth) : tuple of np.ndarray
        ``Y`` shape ``(2 * n_bs, n_train)``; ``S`` shape ``(p, n_train)``;
        ``H_truth`` shape ``(2 * n_bs, p)``.  All real-valued.

    Raises
    ------
    FileNotFoundError
        If the environment directory or channel file does not exist.
    ValueError
        If ``freq_ghz`` is unsupported or channel has zero norm.
    """
    data_dir = Path(data_dir)
    env_path = _env_dir(data_dir, env_id)
    if not env_path.exists():
        raise FileNotFoundError(f"WAIR-D environment directory not found: {env_path}")

    H_complex = _load_channel_matrix(env_path, freq_ghz)  # (n_bs, n_ue)
    n_bs, n_ue = H_complex.shape

    if n_ue < p:
        raise ValueError(
            f"Environment {env_id} has only {n_ue} UE positions; need p={p}."
        )

    # Select p UE columns deterministically from seed.
    rng_ue = np.random.default_rng(seed + 2)
    col_idx = rng_ue.choice(n_ue, size=p, replace=False)
    H_sub = H_complex[:, col_idx]              # (n_bs, p) complex

    H_truth = _real_equiv(H_sub)               # (2*n_bs, p) real
    k = H_truth.shape[0]

    H_norm = float(np.linalg.norm(H_truth))
    if H_norm <= 0.0:
        raise ValueError(f"Environment {env_id}: channel has zero Frobenius norm.")
    H_truth = H_truth / H_norm

    rng_S = np.random.default_rng(seed)
    S = rng_S.standard_normal((p, n_train)).astype(np.float64)
    HS = H_truth @ S                           # (k, n_train)

    if noise_kind.startswith("student_t_"):
        df = float(noise_kind.split("_")[-1])
        rng_n = np.random.default_rng(seed + 1)
        z = rng_n.standard_normal((k, n_train))
        chi2 = rng_n.chisquare(df=df, size=(k, n_train))
        N_unit = (z / np.sqrt(chi2 / df)).astype(np.float64)
    elif noise_kind == "matrix_mal":
        alpha_used = max(alpha_mal, (k - 1) / 2.0 + 0.05)
        if alpha_used != alpha_mal:
            logger.info(
                "alpha_mal=%.3f clipped to %.3f for k=%d.",
                alpha_mal, alpha_used, k,
            )
        N_unit = sample_matrix_mal(
            n_samples=1, k=k, n=n_train, alpha=alpha_used, seed=seed + 1,
        )[0]
    else:
        raise ValueError(
            f"Unsupported noise_kind={noise_kind!r}; "
            f"expected 'matrix_mal' or 'student_t_<df>'."
        )

    N = _scale_noise_to_snr(HS, N_unit, snr_db)
    Y = HS + N
    return Y, S, H_truth
